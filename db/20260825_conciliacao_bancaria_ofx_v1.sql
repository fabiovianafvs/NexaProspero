CREATE TABLE IF NOT EXISTS finance_bank_reconciliation_imports (
  id INT NOT NULL AUTO_INCREMENT,
  company_id INT NOT NULL,
  bank_account_id INT NOT NULL,
  file_name VARCHAR(255) NOT NULL,
  file_hash CHAR(64) NOT NULL,
  bank_code VARCHAR(20) NULL,
  agency VARCHAR(40) NULL,
  account_number VARCHAR(80) NULL,
  account_type VARCHAR(30) NULL,
  date_start DATE NULL,
  date_end DATE NULL,
  transaction_count INT NOT NULL DEFAULT 0,
  imported_count INT NOT NULL DEFAULT 0,
  duplicate_count INT NOT NULL DEFAULT 0,
  total_credits DECIMAL(15,2) NOT NULL DEFAULT 0,
  total_debits DECIMAL(15,2) NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'IMPORTADO',
  imported_by_user_id INT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_fin_recon_import_file (company_id, bank_account_id, file_hash),
  KEY idx_fin_recon_import_date (company_id, bank_account_id, date_start, date_end)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS finance_bank_reconciliation_items (
  id INT NOT NULL AUTO_INCREMENT,
  company_id INT NOT NULL,
  import_id INT NOT NULL,
  bank_account_id INT NOT NULL,
  transaction_key CHAR(64) NOT NULL,
  fitid VARCHAR(180) NULL,
  trn_type VARCHAR(40) NULL,
  posted_date DATE NOT NULL,
  amount DECIMAL(15,2) NOT NULL,
  direction VARCHAR(20) NOT NULL,
  name VARCHAR(500) NULL,
  memo VARCHAR(500) NULL,
  checknum VARCHAR(120) NULL,
  refnum VARCHAR(180) NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
  suggested_origin_type VARCHAR(30) NULL,
  suggested_origin_id INT NULL,
  suggested_score INT NULL,
  reconciliation_mode VARCHAR(30) NULL,
  matched_origin_type VARCHAR(30) NULL,
  matched_origin_id INT NULL,
  settlement_id INT NULL,
  movement_id INT NULL,
  reconciled_at DATETIME NULL,
  reconciled_by_user_id INT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_fin_recon_transaction (company_id, bank_account_id, transaction_key),
  KEY idx_fin_recon_pending (company_id, bank_account_id, status, posted_date),
  KEY idx_fin_recon_import (company_id, import_id),
  KEY idx_fin_recon_match (company_id, matched_origin_type, matched_origin_id),
  KEY idx_fin_recon_movement (company_id, movement_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
