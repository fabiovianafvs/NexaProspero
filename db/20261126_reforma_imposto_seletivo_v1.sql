-- Reforma Tributária: Imposto Seletivo (IS) na NF-e/NFC-e - v1
-- Idempotente. Tabelas de referência globais (iguais para todas as empresas), copiadas da
-- base oficial da Calculadora de Tributos da Receita Federal (calculadora-rtc v1.7.2, base V0073):
--   fiscal_is_cst              = CST do IS (000 a 600)
--   fiscal_is_classifications  = cClassTrib do IS (29 códigos), vigência a partir de 01/01/2027
--   fiscal_is_class_ncm        = NCMs (prefixos) em que cada cClassTrib pode ser usado
--   fiscal_is_ncm_rates        = NCMs sujeitos ao IS (alíquota ad valorem ou ad rem); rate NULL = alíquota
--                                ainda não definida em lei (a empresa informa no produto/tributação)
--   fiscal_is_ncm_exceptions   = NCMs excluídos da incidência
-- Colunas novas (sem mexer nas existentes): seletivo_* em fiscal_product_tax e fiscal_tax_profiles
-- e total_is em fiscal_documents.

CREATE TABLE IF NOT EXISTS `fiscal_is_cst` (
  `cst_code` CHAR(3) NOT NULL,
  `description` VARCHAR(120) NOT NULL,
  `validity_start` DATE NOT NULL,
  `validity_end` DATE NULL,
  PRIMARY KEY (`cst_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `fiscal_is_classifications` (
  `class_code` CHAR(6) NOT NULL,
  `cst_code` CHAR(3) NOT NULL,
  `description` VARCHAR(600) NOT NULL,
  `with_calculation` TINYINT(1) NOT NULL DEFAULT 0,
  `validity_start` DATE NOT NULL,
  `validity_end` DATE NULL,
  PRIMARY KEY (`class_code`),
  KEY `idx_fiscal_is_class_cst` (`cst_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `fiscal_is_class_ncm` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `class_code` CHAR(6) NOT NULL,
  `ncm_prefix` VARCHAR(8) NOT NULL,
  `validity_start` DATE NOT NULL,
  `validity_end` DATE NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `ux_fiscal_is_class_ncm` (`class_code`,`ncm_prefix`,`validity_start`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `fiscal_is_ncm_rates` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `ncm_prefix` VARCHAR(8) NOT NULL,
  `rate_type` VARCHAR(12) NOT NULL,
  `unit` VARCHAR(6) NULL,
  `rate` DECIMAL(9,4) NULL,
  `validity_start` DATE NOT NULL,
  `validity_end` DATE NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `ux_fiscal_is_ncm_rates` (`ncm_prefix`,`rate_type`,`validity_start`),
  KEY `idx_fiscal_is_ncm_rates_prefix` (`ncm_prefix`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `fiscal_is_ncm_exceptions` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `ncm_prefix` VARCHAR(8) NOT NULL,
  `base_prefix` VARCHAR(8) NOT NULL,
  `rate_type` VARCHAR(12) NOT NULL,
  `validity_start` DATE NOT NULL,
  `validity_end` DATE NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `ux_fiscal_is_ncm_exc` (`ncm_prefix`,`base_prefix`,`rate_type`,`validity_start`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

